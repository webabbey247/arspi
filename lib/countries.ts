/**
 * Countries with their ISO-3166 alpha-2 code and ITU dialling code.
 *
 * Static rather than fetched. The reference implementation this was ported
 * from called a third-party API (countriesnow.space) on every mount and fell
 * back to seven countries when it failed — which means a user in a country
 * outside that seven could not enter their own number whenever the service
 * was down. The list changes about once a decade; shipping it costs a few KB
 * and removes a runtime dependency on someone else's uptime.
 *
 * Generated from Intl.DisplayNames, so names are spelled the way the platform
 * spells them. 240 entries.
 */

export type Country = {
  /** ISO-3166 alpha-2, e.g. "NG". */
  iso2:     string
  /** Dialling code including the plus, e.g. "+234". */
  dialCode: string
  name:     string
}

/** Emoji flag from an ISO-3166 alpha-2 code (regional indicator symbols). */
export function flagOf(iso2: string): string {
  if (!/^[A-Za-z]{2}$/.test(iso2)) return "\u{1F3F3}\uFE0F"
  return String.fromCodePoint(
    ...[...iso2.toUpperCase()].map(c => 0x1f1e6 + c.charCodeAt(0) - 65),
  )
}

/** Several countries share a dialling code (+1, +44, +7), so a code alone
 *  cannot identify a country. This picks the one people mean by default. */
const PRIMARY_FOR_CODE: Record<string, string> = {
  "+1": "US", "+44": "GB", "+7": "RU", "+39": "IT", "+47": "NO",
  "+262": "RE", "+590": "GP", "+599": "CW", "+358": "FI",
}

/** The country to show for a dialling code, preferring the primary one. */
export function countryForDialCode(dialCode: string, fallback = "NG"): string {
  const primary = PRIMARY_FOR_CODE[dialCode]
  if (primary) return primary
  return COUNTRIES.find(c => c.dialCode === dialCode)?.iso2 ?? fallback
}

